def draw_header(p, title, user_email):
    """Draws a standardized header on a PDF canvas."""
    width, height = letter
    p.setFont("Helvetica-Bold", 18)
    p.drawString(inch, height - inch, title)
    p.setFont("Helvetica", 10)
    p.drawString(inch, height - 1.25 * inch, f"Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    p.drawString(inch, height - 1.40 * inch, f"Generated by: {user_email}")
    p.line(inch, height - 1.55 * inch, width - inch, height - 1.55 * inch)
    return height - 2 * inch # Return starting y_position

def create_summary_pdf(metrics: dict, user_email: str) -> io.BytesIO:
    """Creates the Executive Summary PDF (already implemented and working)."""
    buffer = io.BytesIO()
    p = canvas.Canvas(buffer, pagesize=letter)
    y_position = draw_header(p, "Executive Summary Report", user_email)

    styles = getSampleStyleSheet()
    
    # Project KPIs
    p.setFont("Helvetica-Bold", 14)
    p.drawString(inch, y_position, "Project Health")
    y_position -= 0.3 * inch
    project_stats = metrics.get('project_stats', {})
    project_kpis = [ f"<b>Total Projects:</b> {project_stats.get('total_projects', 0)}", f"<b>Active Projects:</b> {project_stats.get('active_projects', 0)}", f"<b>- On Track:</b> {project_stats.get('on_track', 0)}", f"<b>- At Risk:</b> {project_stats.get('at_risk', 0)}", f"<b>- Delayed:</b> {project_stats.get('delayed', 0)}" ]
    for kpi in project_kpis:
        para = Paragraph(kpi, styles['Normal'])
        para.wrapOn(p, 5 * inch, 10 * inch)
        para.drawOn(p, 1.2 * inch, y_position)
        y_position -= para.height + 5

    y_position -= 0.5 * inch
    
    # Sales & Leads KPIs
    p.setFont("Helvetica-Bold", 14)
    p.drawString(inch, y_position, "Sales & Leads Performance")
    y_position -= 0.3 * inch
    lead_stats = metrics.get('lead_stats', {})
    lead_kpis = [ f"<b>Total Leads:</b> {lead_stats.get('total_leads', 0)}", f"<b>Pipeline Value (Active):</b> ₹{lead_stats.get('pipeline_value', 0):,}", f"<b>Total Revenue (Won):</b> ₹{lead_stats.get('total_revenue', 0):,}", f"<b>Conversion Rate:</b> {lead_stats.get('conversion_rate', 0)}%" ]
    for kpi in lead_kpis:
        para = Paragraph(kpi, styles['Normal'])
        para.wrapOn(p, 5 * inch, 10 * inch)
        para.drawOn(p, 1.2 * inch, y_position)
        y_position -= para.height + 5

    p.showPage()
    p.save()
    buffer.seek(0)
    return buffer

def create_project_health_pdf(projects: List[Dict], user_email: str) -> io.BytesIO:
    """
    FEATURE: Generates a detailed, multi-page Project Health PDF with tables.
    """
    buffer = io.BytesIO()
    p = canvas.Canvas(buffer, pagesize=landscape(letter)) # Use landscape for wider tables
    width, height = landscape(letter)
    
    y_position = draw_header(p, "Project Health Report", user_email)

    statuses_to_report = ["On Track", "At Risk", "Delayed", "Completed"]
    
    for status in statuses_to_report:
        projects_in_status = [proj for proj in projects if proj.get('status') == status]
        if not projects_in_status:
            continue

        p.setFont("Helvetica-Bold", 14)
        p.drawString(inch, y_position, f"Status: {status} ({len(projects_in_status)} Projects)")
        y_position -= 0.4 * inch

        table_data = [
            ["Project Name", "Client", "Owner", "Completion", "Budget (INR)"]
        ]
        for proj in projects_in_status:
            table_data.append([
                proj.get('name', '-'),
                proj.get('client', '-'),
                proj.get('owner', '-'),
                f"{proj.get('completion', 0)}%",
                f"₹{proj.get('budget', 0):,}"
            ])
        
        table = Table(table_data, colWidths=[2.5*inch, 2*inch, 1.5*inch, 1*inch, 1.5*inch])
        table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.grey),
            ('TEXTCOLOR', (0,0), (-1,0), colors.whitesmoke),
            ('ALIGN', (0,0), (-1,-1), 'LEFT'),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('BOTTOMPADDING', (0,0), (-1,0), 12),
            ('BACKGROUND', (0,1), (-1,-1), colors.beige),
            ('GRID', (0,0), (-1,-1), 1, colors.black)
        ]))

        # Check if table fits on page, otherwise start a new page
        table_height = table.wrap(width - 2*inch, height)[1]
        if y_position - table_height < inch:
            p.showPage()
            y_position = height - 1.5 * inch

        table.drawOn(p, inch, y_position - table_height)
        y_position -= table_height + 0.5 * inch

    p.showPage()
    p.save()
    buffer.seek(0)
    return buffer

