# --- Background Task (Unchanged) ---
def generate_and_upload_report(report_id: str, report_name: str, report_type: str, user_email: str):
    print(f"BACKGROUND TASK STARTED for report {report_id} by {user_email}")
    try:
        all_projects = db_service.get_all_projects()
        all_leads = db_service.get_all_leads()
        project_stats = db_service.get_project_statistics()
        lead_stats = db_service.get_lead_statistics()
        all_metrics = { "project_stats": project_stats, "lead_stats": lead_stats }
        
        pdf_buffer = None
        if report_type == "Project Health":
            pdf_buffer = create_project_health_pdf(all_projects, user_email)
        elif report_type == "Leads & Sales":
            pdf_buffer = create_leads_sales_pdf(all_leads, lead_stats, user_email)
        else:
            pdf_buffer = create_summary_pdf(all_metrics, user_email)
        
        pdf_content = pdf_buffer.getvalue()
        file_path = f"generated/{report_id}.pdf"
        supabase.storage.from_("reports").upload(file=pdf_content, path=file_path, file_options={"content-type": "application/pdf", "upsert": "true"})
        public_url = supabase.storage.from_("reports").get_public_url(file_path)
        db_service.update_report_record(report_id, { "status": "Success", "download_url": public_url })
        print(f"BACKGROUND TASK COMPLETED SUCCESSFULLY for report {report_id}")

    except Exception as e:
        print(f"!!! BACKGROUND TASK FAILED for report {report_id} !!! ERROR: {e}")
        db_service.update_report_record(report_id, {"status": "Failed"})

# --- API Endpoints ---
@router.get("", response_model=List[Report])
async def get_reports(user: dict = Depends(get_current_user)):
    try:
        return db_service.get_all_reports()
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@router.post("/generate", response_model=Report, status_code=status.HTTP_202_ACCEPTED)
async def generate_new_report(
    report_data: ReportCreate,
    background_tasks: BackgroundTasks,
    user: dict = Depends(get_current_user)
):
    try:
        user_email = user.get('email', 'Unknown User')
        data_to_insert = report_data.model_dump()
        report_id = f"rep_{uuid4().hex[:8]}"
        data_to_insert["id"] = report_id
        data_to_insert["status"] = "Pending"
        data_to_insert["generated_by"] = user_email
        data_to_insert["generated_on"] = datetime.now().date().isoformat()
        
        new_report_record = db_service.create_report_record(data_to_insert)
        if not new_report_record:
            raise HTTPException(status_code=500, detail="Failed to create initial report record.")

        background_tasks.add_task(generate_and_upload_report, report_id, report_data.name, report_data.type, user_email)
        
        return Report.model_validate(new_report_record)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"An error occurred: {str(e)}")

# --- NEW: Secure endpoint to delete a report ---
@router.delete("/{report_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_report(
    report_id: str,
    user: dict = Depends(get_current_user)
):
    """
    Deletes a report record from the database and the associated file from storage.
    """
    try:
        success = db_service.delete_report(report_id)
        if not success:
            # This handles the case where the report ID does not exist.
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Report with ID '{report_id}' not found.")
        # A 204 response has no body, so we return None.
        return None
    except Exception as e:
        # This will catch any unexpected errors from the database service.
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An unexpected error occurred: {str(e)}")

